/** Руководство по написанию и установке скилов, которое показывает
 * `SkillsGuideModal`. Живёт отдельно от компонента: это контент, а не
 * разметка, и все правила ниже должны совпадать с проверками в
 * `domain::agent_skills` (имя, описание, frontmatter) и с тем, что делает
 * импорт в `infra::user_skills_store`. */
export const SKILLS_GUIDE_MD = `## Что такое скил

Скил — папка с инструкциями, которую ассистент подгружает **по требованию**, а не
держит в контексте постоянно. Внутри — файл \`SKILL.md\` и, если нужно, дополнительные
файлы: справочники, шаблоны, примеры.

Ассистент работает со скилом в три шага:

1. **Ищет** подходящий скил по имени и описанию — в контекст попадают только эти две
   строки, тела скилов не загружаются.
2. **Загружает** тело \`SKILL.md\` найденного скила.
3. **Дочитывает** вложенные файлы, если тело на них ссылается.

Отсюда главное правило: **описание решает, найдётся ли скил вообще**. Пишите в нём,
*когда* применять скил, а не только *что* он делает.

## Структура папки

\`\`\`text
method-spec/
├── SKILL.md              # обязателен, имя файла — ровно так
├── references/
│   ├── structure.md      # вложенные файлы — любые текстовые
│   └── errors.md
└── assets/
    └── template.adoc
\`\`\`

Имя папки должно совпадать с полем \`name\` внутри \`SKILL.md\` — иначе скил попадёт
в список с ошибкой и работать не будет. Вложенные файлы необязательны; подпапки
любой глубины разрешены.

## Формат SKILL.md

Файл начинается с YAML-фронтматтера между двумя строками \`---\`, дальше идёт обычный
Markdown — это и есть инструкции для ассистента.

\`\`\`markdown
---
name: method-spec
description: Заполнение документации REST-метода — структура разделов, коды ошибок,
  глоссарий. Использовать, когда просят описать или дополнить метод API.
---

# Как заполнять описание метода

1. Возьми шаблон из \`assets/template.adoc\`.
2. Проверь структуру разделов по \`references/structure.md\`.
3. Коды ошибок бери из \`references/errors.md\`, не придумывай свои.
\`\`\`

### Обязательные поля

| Поле | Правила |
| --- | --- |
| \`name\` | 1–64 символа; только строчные латинские буквы, цифры и дефис; без дефиса в начале и конце и без двух дефисов подряд; совпадает с именем папки |
| \`description\` | 1–1024 символа; по нему идёт поиск — укажите задачу и повод применить скил |

Поля \`license\`, \`compatibility\`, \`metadata\` и \`allowed-tools\` разрешены, но
приложение их не использует. Любые другие поля тоже не мешают.

### Тело

Всё после закрывающего \`---\` — инструкции ассистенту. Пишите их как указания
исполнителю: шаги, правила, запреты, примеры. На вложенные файлы ссылайтесь
относительным путём от корня скила (\`references/errors.md\`) — ассистент прочитает
их сам, когда дойдёт до этого шага. Выносите во вложенные файлы всё объёмное:
тело скила загружается целиком, а справочник — только при необходимости.

## Как загрузить скил

1. Нажмите **Добавить скил** и выберите **папку** скила — не сам \`SKILL.md\`.
2. Папка целиком копируется в \`~/.atlas/skills/<name>/\`. Оригинал остаётся
   на месте, дальнейшие правки в нём на приложение не влияют.
3. Скил появляется в списке и сразу включён.

Импорт откажет, если в папке нет \`SKILL.md\`, если фронтматтер не проходит проверки
выше или если скил с таким именем уже установлен — сначала удалите старый.

Кнопка **Открыть папку** показывает \`~/.atlas/skills\` в файловом менеджере: там
скилы можно править и добавлять вручную, без импорта. Список читается заново при
каждом открытии настроек.

## Включение, замена, удаление

- Флажок слева выключает скил: выключенный не находится поиском и не загружается.
- Скил с именем встроенного **заменяет** его — так встроенный скил можно
  переопределить своей версией.
- Кнопка **Удалить** есть только у пользовательских скилов и стирает папку с диска.
- Кнопка с глазом открывает содержимое скила: файлы слева, текст справа.
  Просмотр доступен и для выключенного, и для сломанного скила — так видно,
  что именно в нём не так.

## Если скил показан с ошибкой

Красная строка вместо описания означает, что \`SKILL.md\` не разобрался. Частые причины:

- нет фронтматтера или первая строка файла не \`---\`;
- \`name\` не совпадает с именем папки;
- в \`name\` заглавные буквы, пробелы или подчёркивания;
- пустое \`description\`;
- сломанный YAML — например, двоеточие в значении без кавычек.

## Короткий чеклист

- [ ] Папка названа так же, как \`name\`
- [ ] Внутри есть \`SKILL.md\` с \`name\` и \`description\`
- [ ] В описании сказано, **когда** применять скил
- [ ] Объёмные справочники вынесены в отдельные файлы и упомянуты в теле
- [ ] Скил добавлен через **Добавить скил** и виден в списке без ошибки
`;
